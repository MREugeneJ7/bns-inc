const EGG_BASE: string[] = [
  '.....dddd.....',
  '...ddaadd.....',
  '..daaaaaad....',
  '.daaaaaaaad...',
  '.daaaaaaaad...',
  'daaaaaaaaaaad.',
  'daaaaaaaaaaaad',
  'daaaaaaaaaaaad',
  'daaaaaaaaaaaad',
  'daaaaaaaaaaaad',
  '.daaaaaaaaaad.',
  '.daaaaaaaaaad.',
  '..daaaaaaaad..',
  '...daaaaaad...',
  '.....dddd.....',
];

function makeEgg(spots: [number, number][], shellDark = false): CreatureSprite {
  const set = new Set(spots.map(([x, y]) => `${x},${y}`));
  return EGG_BASE.map((row, y) =>
    row
      .split('')
      .map((ch, x) => {
        if (ch !== 'a') return ch;
        if (set.has(`${x},${y}`)) return shellDark ? 'c' : 'b';
        return shellDark ? 'b' : 'a';
      })
      .join('')
  );
}


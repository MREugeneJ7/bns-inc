export function drawCreature(
  ctx: CanvasRenderingContext2D,
  id: string,
  x: number,
  y: number,
  scale = 1,
  cell = CELL
) {
  const spr = CREATURES[id];
  if (!spr) return;
  const w = Math.max(...spr.map((r) => r.length));
  const h = spr.length;
  const ox = x + Math.floor(((cell - w) / 2) * scale);
  const oy = y + Math.floor(((cell - h) / 2) * scale);
  for (let r = 0; r < h; r++) {
    const row = spr[r];
    for (let c = 0; c < row.length; c++) {
      const ch = row[c];
      if (ch === '.' || ch === undefined) continue;
      ctx.fillStyle = PAL[CH[ch]];
      ctx.fillRect(ox + c * scale, oy + r * scale, scale, scale);
    }
  }
}

// DataURL cache for the React battle UI (nearest-neighbour upscale via CSS).
const urlCache: Record<string, string> = {};
export function creatureURL(id: string): string {
  if (urlCache[id]) return urlCache[id];
  const cv = document.createElement('canvas');
  cv.width = CELL; cv.height = CELL;
  const ctx = cv.getContext('2d')!;
  drawCreature(ctx, id, 0, 0, 1);
  const url = cv.toDataURL();
  urlCache[id] = url;
  return url;
}

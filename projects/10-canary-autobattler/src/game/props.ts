// Chino de Taco: 16x16, gorra, visera, delantal.
export const CHINO: string[] = Array.from({ length: 16 }, (_, y) =>
  Array.from({ length: 16 }, (_, x) => {
    const dx = Math.abs(x - 7.5);
    if (y >= 1 && y <= 3 && dx <= 5) return y === 1 ? 'd' : 'c';
    if (y === 4 && dx <= 6) return 'd';
    if (y >= 5 && y <= 8 && dx <= 4) return y === 6 && (x === 5 || x === 10) ? 'd' : 'a';
    if (y === 8 && dx <= 1.5) return 'd';
    if (y >= 9 && y <= 13 && dx <= 5) return dx <= 3 && y >= 10 ? 'b' : 'c';
    if (y >= 14 && dx <= 4) return y === 15 ? 'd' : 'c';
    return '.';
  }).join('')
);

/** Tranvia de la Linea 1: 64x32 (4x2 tiles). La puerta ocupa la columna 16..31 (x+1). */
export function drawTram(ctx: CanvasRenderingContext2D, x: number, y: number, frame: number) {
  const R = (rx: number, ry: number, rw: number, rh: number, c: number) => {
    ctx.fillStyle = PAL[c];
    ctx.fillRect(x + rx, y + ry, rw, rh);
  };
  R(0, 1, 64, 29, 3);
  R(1, 2, 62, 27, 2);
  R(1, 0, 62, 3, 3);
  R(24, 0, 16, 2, 0);
  R(1, 14, 62, 1, 3);
  for (const wx of [3, 36, 49]) {
    R(wx, 5, 11, 8, 3);
    R(wx + 1, 6, 9, 6, 0);
    R(wx + 1, 6, 3, 6, 1);
  }
  R(15, 12, 18, 18, 3);
  R(16, 13, 16, 17, 1);
  R(18, 15, 12, 6, 0);
  R(18, 23, 12, 1, 3);
  R(1, 26, 62, 2, 3);
  R(6, 28, 9, 4, 3);
  R(49, 28, 9, 4, 3);
  R(0, 22, 2, 3, frame % 30 < 15 ? 0 : 1);
  R(62, 22, 2, 3, 0);
}


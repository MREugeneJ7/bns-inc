/**
 * Carreta de Romeria con Yunta de Bueyes y Barrica de Vino Peleon: 48x32 (3x2 tiles).
 * Corta la entrada a Adeje en la TF-1 y aparca en la Estacion de Las Americas.
 */
export function drawCarretaRomera(ctx: CanvasRenderingContext2D, x: number, y: number, frame: number) {
  const sway = Math.floor(frame / 14) % 2;
  const R = (rx: number, ry: number, rw: number, rh: number, c: number) => {
    ctx.fillStyle = PAL[c];
    ctx.fillRect(x + rx, y + ry + sway, rw, rh);
  };
  // Banderines de romeria y toldo engalanado de la carreta (derecha: x+18..46)
  R(18, 2, 28, 4, 3);
  for (let bx = 20; bx <= 42; bx += 4) R(bx, 3, 2, 2, (bx / 4) % 2 === 0 ? 0 : 1);
  // Barrica de Vino Peleon encima de la carreta + caja de madera
  R(24, 6, 16, 8, 3);
  R(26, 7, 12, 6, 2);
  R(28, 9, 8, 2, 0);
  R(18, 13, 28, 10, 3);
  R(20, 14, 24, 8, 1);
  for (let px = 22; px <= 40; px += 4) R(px, 15, 2, 6, 2);
  // Rueda grande de madera con radios (x+27..37, y+21..29)
  ctx.fillStyle = PAL[3];
  ctx.fillRect(x + 26, y + 20, 12, 10);
  ctx.fillStyle = PAL[0];
  ctx.fillRect(x + 28, y + 22, 8, 6);
  ctx.fillStyle = PAL[3];
  ctx.fillRect(x + 31, y + 22, 2, 6);
  ctx.fillRect(x + 28, y + 24, 8, 2);

  // Yugo y Yunta de Bueyes a la izquierda (x+1..18)
  R(14, 15, 6, 3, 3); // lanza y yugo
  R(2, 10, 4, 3, 0); R(11, 10, 4, 3, 0); // cuernos blancos
  R(3, 12, 12, 11, 3);
  R(4, 13, 10, 9, 2);
  R(5, 14, 8, 3, 0); // frontil canario bordado
  R(5, 18, 2, 2, 3); R(10, 18, 2, 2, 3); // ojos
  R(5, 20, 8, 2, 1); // morro
  // Patas de la yunta
  ctx.fillStyle = PAL[3];
  ctx.fillRect(x + 4, y + 23, 3, 6);
  ctx.fillRect(x + 11, y + 23, 3, 6);
}

/**
 * Cutscene de la Romeria de Adeje -> Estacion de Las Americas al toque de Bucio e Isa Canaria.
 */
export function drawRomeriaCutscene(
  ctx: CanvasRenderingContext2D,
  W: number,
  H: number,
  stage: 'bucio' | 'isa' | 'arrival',
  t: number,
) {
  const R = (x: number, y: number, w: number, h: number, c: number) => {
    ctx.fillStyle = PAL[c];
    ctx.fillRect(Math.round(x), Math.round(y), Math.round(w), Math.round(h));
  };
  const txt = (s: string, x: number, y: number, c = 3) => {
    ctx.fillStyle = PAL[c];
    ctx.fillText(s, Math.round(x), Math.round(y));
  };

  // Fondo festivo con guirnaldas de romeria arriba
  R(0, 0, W, H, 0);
  R(0, 0, W, 30, 3);
  for (let gx = 8; gx < W - 8; gx += 16) {
    const drop = (gx / 16 + Math.floor(t / 10)) % 2 === 0 ? 18 : 22;
    R(gx, 6, 10, drop, 1);
    R(gx + 2, 8, 6, drop - 4, 0);
  }

  // Suelo de adoquines y carretera con confeti y hojas de pino
  R(0, 182, W, H - 182, 2);
  R(0, 182, W, 4, 3);
  for (let i = 0; i < 18; i++) {
    const cx = ((i * 37 - t * 2) % W + W) % W;
    const cy = 192 + (i % 4) * 14;
    R(cx, cy, 8, 3, i % 2 === 0 ? 1 : 0);
  }

  if (stage === 'bucio') {
    // Etapa 1: El guirufo sopla el Bucio de Las Teresitas a pleno pulmon y se infiltra en la romeria
    R(24, 38, W - 48, 30, 3);
    R(26, 40, W - 52, 26, 0);
    txt('SOPLAS EL BUCIO DE LAS TERESITAS!', 34, 46, 3);
    txt('BOOOOOOO-UUUUUUUUU!!', 84, 56, 2);

    // Guirufo en el centro con el bucio y ondas sonoras expansivas
    const bob = Math.floor(t / 6) % 2 * 2;
    R(116, 108 + bob, 28, 10, 3); // gorra/cachorro improvisado
    R(120, 118 + bob, 20, 18, 0);
    R(118, 136 + bob, 24, 28, 2);
    R(120, 164, 8, 18, 3); R(132, 164, 8, 18, 3);
    // El Bucio (caracola) en la boca
    R(142, 120 + bob, 18, 12, 3);
    R(144, 122 + bob, 14, 8, 1);
    R(152, 118 + bob, 8, 16, 3);
    // Ondas de sonido del bucio
    for (let w = 0; w < 3; w++) {
      const dist = ((t * 2 + w * 18) % 54);
      R(164 + dist, 112 - w * 4, 4, 28 + w * 8, 3);
    }

    // Romeros alrededor levantando vasos de vino peleon
    for (const rx of [48, 236]) {
      R(rx - 4, 112 - bob, 28, 6, 3);
      R(rx, 118 - bob, 20, 16, 0);
      R(rx, 134 - bob, 20, 28, 3);
      R(rx + 4, 138 - bob, 12, 12, 0);
      R(rx + 22, 118 - bob, 6, 10, 3); // cuarta de vino en alto!
    }

    R(14, 204, W - 28, 44, 3);
    R(16, 206, W - 32, 40, 0);
    txt('ROMERO: "Chacho, este toca el bucio', 24, 214, 3);
    txt('como un cabrero! Denle vino peleon', 24, 226, 3);
    txt('y metanlo en la carreta pa Las Americas!"', 24, 238, 2);
  } else if (stage === 'isa') {
    // Etapa 2: Desfile de la Romeria con la Yunta de Bueyes, la Barrica y la Isa Canaria a todo trapo
    R(18, 36, W - 36, 28, 3);
    R(20, 38, W - 40, 24, 0);
    txt('♪ SUENA UNA ISA CANARIA A 3 POR 4 ♫', 26, 43, 3);
    txt('RUMBO A LA ESTACION DE LAS AMERICAS', 26, 53, 2);

    // Notas musicales flotando por el aire
    for (let n = 0; n < 6; n++) {
      const nx = ((n * 54 + t * 2) % (W - 24)) + 12;
      const ny = 74 + Math.sin(t * 0.15 + n) * 10;
      txt(n % 2 === 0 ? '♪' : '♫', nx, ny, 3);
    }

    // Carreta Romera gigante + Yunta de Bueyes avanzando en procesion
    const marchX = 68 + Math.sin(t * 0.08) * 10;
    ctx.save();
    ctx.translate(marchX, 94);
    ctx.scale(2, 2);
    drawCarretaRomera(ctx, 0, 0, t);
    ctx.restore();

    // Romeros bailando la Isa detras y delante de la carreta
    const stepDance = Math.floor(t / 8) % 2 === 0 ? -3 : 3;
    for (const dx of [24, 204, 252]) {
      R(dx - 2, 118 + stepDance, 24, 6, 3); // cachorro canario
      R(dx + 2, 124 + stepDance, 16, 14, 0);
      R(dx, 138 + stepDance, 20, 24, 3);
      R(dx + 4, 140 + stepDance, 12, 10, 1);
      R(dx + 2, 162, 6, 16, 3); R(dx + 12, 162, 6, 16, 3);
    }

    const copla = Math.floor(t / 55) % 2 === 0
      ? ['♪ "Esta noche no alumbro yo', '   por no tener gasoil en el candil..." ♫']
      : ['♪ "Quien quiera beber vino peleon', '   que se arrime a la Yunta de Adeje!" ♫'];
    R(14, 200, W - 28, 48, 3);
    R(16, 202, W - 32, 44, 0);
    txt(copla[0], 24, 210, 3);
    txt(copla[1], 24, 222, 3);
    txt('(A: cantar y seguir · Te dan medio huevo duro)', 22, 236, 2);
  } else {
    // Etapa 3: Fin de la Romeria en la Estacion de Guaguas de Las Americas
    R(22, 42, W - 44, 32, 3);
    R(24, 44, W - 48, 28, 0);
    txt('FIN DE LA ROMERIA:', 92, 50, 3);
    txt('ESTACION DE LAS AMERICAS!', 64, 62, 2);

    drawCarretaRomera(ctx, 136, 118, t);
    R(16, 202, W - 32, 42, 3);
    R(18, 204, W - 36, 38, 0);
    txt('Un MAGO con garrote se planta', 48, 212, 3);
    txt('frente al arco de CIUDAD FUCSIA... Adeje!', 22, 226, 2);
  }
}

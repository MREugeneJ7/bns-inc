/**
 * Cinematica Game Boy (320x288): "EL FEVER DREAM DEL CAYUCO".
 * stage:
 *  - 'storm'  : mar todo picao, cayuco de chapas dando leñazos, fueraborda a 120dB y humo negro en tu oido.
 *  - 'dream'  : alucinacion febril por humo de mezcla + 120dB (paleta invertida, peces volando, el Armas).
 *  - 'vomit'  : muelle de llegada, potando doblado por la borda del pantalan.
 *  - 'after'  : de pie temblando y verde en el muelle ("Chacho, hasta el Armas se mueve menos...").
 */
export function drawCayucoFeverDream(
  ctx: CanvasRenderingContext2D,
  W: number,
  H: number,
  stage: 'storm' | 'dream' | 'vomit' | 'after',
  t: number
) {
  const invert = stage === 'dream' && Math.floor(t / 14) % 2 === 0;
  const P = invert ? [PAL[3], PAL[2], PAL[1], PAL[0]] : PAL;
  const R = (x: number, y: number, w: number, h: number, c: number) => {
    ctx.fillStyle = P[c];
    ctx.fillRect(Math.round(x), Math.round(y), Math.round(w), Math.round(h));
  };
  const txt = (s: string, x: number, y: number, c = 3) => {
    ctx.fillStyle = P[c];
    ctx.fillText(s, Math.round(x), Math.round(y));
  };

  if (stage === 'storm' || stage === 'dream') {
    // Sacudida bestial de 120dB
    const jx = (t % 2 === 0 ? -1 : 1) * (stage === 'dream' ? 3 : 2);
    const jy = (Math.floor(t / 2) % 2 === 0 ? -2 : 2);
    ctx.save();
    ctx.translate(jx, jy);

    // Cielo encapotado de alisio duro
    R(-6, -6, W + 12, H + 12, 0);
    for (let cx = 0; cx < W; cx += 32) {
      const ox = ((cx - t * 2) % (W + 64) + (W + 64)) % (W + 64) - 32;
      R(ox, 18 + (cx % 3) * 8, 42, 10, 1);
      R(ox + 6, 14 + (cx % 3) * 8, 28, 6, 1);
    }

    // En modo FEVER DREAM: silueta fantasma del ferry ARMAS en el cielo + peces volando al reves!
    if (stage === 'dream') {
      const fx = W - ((t * 1.6) % (W + 140)) + 20;
      const fy = 46 + Math.sin(t * 0.15) * 10;
      // Ferry Armas imaginario flotando entre nubes de gasolina
      R(fx, fy + 10, 84, 14, 2);
      R(fx + 10, fy, 56, 10, 1);
      R(fx + 52, fy - 8, 10, 8, 3);
      txt('ARMAS?', fx + 16, fy + 13, 0);
      // Peces y espirales de mareo cruzando el cielo
      for (let i = 0; i < 4; i++) {
        const px = ((t * (2.5 + i * 0.5) + i * 90) % (W + 40)) - 20;
        const py = 54 + Math.sin(t * 0.2 + i * 1.7) * 26;
        R(px, py, 14, 8, 3); R(px + 2, py + 2, 10, 4, 0); R(px - 4, py + 2, 4, 4, 3);
      }
    } else {
      // Silueta del Teide y Anaga alejandose a popa
      R(12, 78, 70, 26, 1);
      R(26, 64, 40, 16, 1);
      R(38, 54, 16, 12, 1);
    }

    // Mar todo picao: 3 capas de olas gigantes
    for (let x = -8; x < W + 16; x += 8) {
      const wBack = 128 + Math.sin(x * 0.045 + t * 0.16) * 14;
      R(x, wBack, 9, H - wBack + 8, 1);
    }

    // Posicion del cayuco cabalgando la ola central
    const bx = 92;
    const waveY = 142 + Math.sin(t * 0.22) * 22 + Math.cos(t * 0.37) * 7;
    const pitch = Math.cos(t * 0.22) * 0.22;

    ctx.save();
    ctx.translate(bx + 64, waveY);
    ctx.rotate(pitch);

    // FUERABORDA YAMAHA DEL 82 temblando a lo loco (a la izquierda, pegado a tu oreja!)
    const mx = -68 + (t % 2) * 2;
    const my = -16 + ((t >> 1) % 2) * 2;
    R(mx, my, 18, 18, 3);
    R(mx + 3, my + 3, 12, 10, 1);
    R(mx + 6, my + 18, 6, 22, 3); // pata del fueraborda
    // Ondas acusticas "120dB" clavandose en tu oido
    if (t % 6 < 3) {
      R(mx + 20, my - 4, 2, 12, 3);
      R(mx + 24, my - 7, 2, 18, 3);
    }

    // NUBARRON DE HUMO NEGRO saliendo del fueraborda directo a tu cara
    for (let i = 0; i < 8; i++) {
      const age = (t * 2 + i * 11) % 88;
      const sx = mx - age * 0.9 + (i % 2 === 0 ? 18 : -4);
      const sy = my - 4 - age * 0.55 + Math.sin(t * 0.3 + i) * 5;
      const sz = 8 + Math.floor(age / 7);
      R(sx, sy, sz, sz, age < 45 ? 3 : 2);
      if (age < 30) R(sx + 2, sy + 2, sz - 4, sz - 4, 2);
    }

    // GUIRUFO justo al lado del fueraborda, verde y agarrado a la chapa
    R(-42, -26, 18, 16, 3); R(-40, -24, 14, 12, 1); // cara verde mareada
    R(-37, -21, 3, 3, 3); R(-31, -21, 3, 3, 3);     // ojos como platos (X_X)
    R(-36, -15, 8, 3, 3);                            // carrillos inflados aguantando la pota
    R(-44, -10, 22, 14, 2);                          // camisa hawaiana empapada

    // CARMELO EL CAYUQUERO tan pancho con su gorro pesquero
    R(6, -30, 22, 6, 3); R(9, -35, 16, 6, 1);       // gorro
    R(9, -24, 16, 14, 0);                            // cara curtida
    R(12, -21, 3, 2, 3); R(19, -21, 3, 2, 3);
    R(9, -15, 16, 6, 3);                             // barba
    R(7, -10, 20, 14, 3);                            // chaleco
    R(-22, -12, 30, 3, 3);                           // caña del timon hasta el fueraborda

    // CASCO DE CHAPAS ABOLLADAS CON REMACHES
    R(-56, 0, 114, 24, 3);
    R(58, -6, 16, 22, 3);
    R(74, -10, 8, 16, 3);
    R(-52, 4, 106, 16, 0);
    R(54, -2, 16, 14, 0);
    // Juntas de chapa, parches de oxido y remaches
    for (const rx of [-32, -8, 18, 42]) {
      R(rx, 4, 2, 16, 3);
      R(rx - 4, 6, 2, 2, 3); R(rx + 4, 15, 2, 2, 3);
    }
    R(-28, 8, 16, 8, 1);
    R(22, 7, 16, 9, 1);
    R(-52, 13, 118, 3, 2);
    ctx.restore();

    // Ola delantera rompiendo por encima con rociones de espuma
    for (let x = -8; x < W + 16; x += 6) {
      const wy = 166 + Math.sin(x * 0.055 + t * 0.24) * 18 + Math.cos(x * 0.11 - t * 0.19) * 6;
      R(x, wy, 7, 6, 0);
      R(x, wy + 5, 7, 14, 2);
      R(x, wy + 18, 7, H - wy, 3);
    }
    // Salpicaduras volando por la cara
    for (let i = 0; i < 10; i++) {
      const sx = ((i * 37 - t * 5) % W + W) % W;
      const sy = 90 + ((i * 53 + t * 3) % 95);
      R(sx, sy, 4, 4, 0);
    }

    // Rotulos temblorosos de 120dB
    R(10, 8, W - 20, 22, 3);
    R(12, 10, W - 24, 18, 0);
    if (stage === 'storm') {
      const loud = Math.floor(t / 10) % 2 === 0 ? 'BRRRRRR!! FUERABORDA 120dB!!' : 'POP-POP-BRRRR!! COF! COF!!';
      txt(loud, 22 + (t % 3), 15, 3);
    } else {
      const hallu = Math.floor(t / 24) % 2 === 0 ? 'CARMELO: QUIERES UN PLATANO?!' : '120dB + HUMO + OLAS DE 4M...';
      txt(hallu, 20, 15, 3);
    }

    ctx.restore();
    return;
  }

  // --- ESCENA DE LLEGADA AL MUELLE (vomit / after) ---
  R(0, 0, W, H, 0);
  // Mar en calma relativa a la izquierda + muelle de piedra a la derecha
  R(0, 118, W, H - 118, 1);
  for (let y = 128; y < 220; y += 18) {
    const o = Math.floor(t / 16) % 2 === 0 ? 0 : 6;
    R(12 + o, y, 28, 3, 0);
    R(68 - o, y + 6, 24, 3, 0);
  }
  // Cayuco de chapas amarrado abajo-izquierda, aun humeando del calenton
  R(18, 148, 86, 20, 3); R(22, 152, 78, 12, 0);
  R(42, 152, 2, 12, 3); R(68, 152, 2, 12, 3);
  R(10, 138, 14, 14, 3); R(12, 140, 10, 8, 2); // fueraborda caliente
  const smY = (t >> 2) % 18;
  R(12, 132 - smY, 8, 6, 2); R(16, 122 - smY, 6, 4, 1);

  // Muelle de piedra de Galdar (solo el borde del pantalan!)
  R(124, 104, W - 124, 122, 3);
  R(128, 108, W - 128, 114, 1);
  for (let mx = 136; mx < W; mx += 28) R(mx, 108, 2, 114, 2);
  R(128, 108, W - 128, 6, 0); // bordillo
  R(134, 142, 10, 14, 3); R(136, 144, 6, 4, 0); // noray de amarre
  R(104, 150, 32, 2, 3); // cabo amarrado

  // Carmelo fresquisimo en el muelle fumando/saludando
  R(226, 116, 22, 6, 3); R(229, 110, 16, 6, 2);
  R(229, 122, 16, 12, 0); R(229, 130, 16, 5, 3);
  R(227, 135, 20, 18, 3); R(229, 153, 6, 10, 3); R(239, 153, 6, 10, 3);

  if (stage === 'vomit') {
    // Guirufo doblado en el borde del muelle echando hasta la primera papilla
    R(146, 122, 24, 14, 2); // espalda doblada
    R(152, 136, 8, 14, 3); R(162, 136, 8, 14, 3); // piernas temblando
    R(130, 120, 16, 14, 3); R(132, 122, 12, 10, 1); // cabeza asomada al agua
    // Arco iris monocromo Game Boy cayendo al agua + salpicon
    const vy = (t * 2) % 24;
    R(116, 132, 14, 5, 3);
    R(112, 136, 8, 22, 2);
    R(114, 136 + (vy % 14), 4, 8, 3);
    R(104, 158, 22, 5, 0); // chof!
    // Estrellitas de mareo
    const sx = Math.cos(t * 0.2) * 10;
    R(144 + sx, 106, 4, 4, 3); R(144 - sx, 102, 4, 4, 3);

    R(18, 16, W - 36, 24, 3); R(20, 18, W - 40, 20, 0);
    txt('TIERRA FIRME... BLAAAARGH!!', 34, 24, 3);
  } else {
    // De pie, palido/ojeroso, limpiandose la boca y dudando de su identidad guiri
    const shiver = Math.floor(t / 6) % 2;
    R(156 + shiver, 108, 18, 6, 3);
    R(156 + shiver, 114, 18, 14, 3); R(158 + shiver, 116, 14, 10, 0);
    R(160 + shiver, 119, 3, 2, 3); R(167 + shiver, 119, 3, 2, 3);
    R(162 + shiver, 123, 6, 2, 2);
    R(155 + shiver, 128, 20, 16, 2);
    R(157 + shiver, 144, 6, 10, 3); R(167 + shiver, 144, 6, 10, 3);
    txt('?', 162, 94 + (Math.floor(t / 15) % 2) * 2, 3);
  }
}

